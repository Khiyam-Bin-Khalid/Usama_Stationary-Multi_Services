const Product = require('../models/Product');
const InventoryLog = require('../models/InventoryLog');
const AppError = require('../utils/AppError');
const { applyStockChange } = require('./inventoryService');
const { INVENTORY_LOG_TYPES } = require('../utils/constants');
const { logAction } = require('./auditService');
const { getCategoryOrThrow } = require('./categoryService');
const { generateSku } = require('./skuService');

// Product writes shared by the REST routes and the offline sync endpoint
// (POST /sync/ops), so a change made offline follows exactly the same rules,
// inventory logging and audit trail as one made online.

// Normalises the three identifiers on create/update payloads:
//  - sku: blank → removed (so the controller auto-generates it)
//  - barcode: blank → unset (sparse unique index must not see '')
function normaliseIdentifiers(payload) {
  const out = { ...payload };
  if (out.sku !== undefined && (out.sku === null || String(out.sku).trim() === '')) delete out.sku;
  if (out.barcode !== undefined && (out.barcode === null || String(out.barcode).trim() === '')) {
    delete out.barcode;
    out.$unset = { ...(out.$unset || {}), barcode: 1 };
  }
  return out;
}

async function createProduct(body, user) {
  const category = await getCategoryOrThrow(body.category);
  const payload = normaliseIdentifiers({ ...body, createdBy: user._id });
  delete payload.$unset;
  if (payload.reorderThreshold === undefined) payload.reorderThreshold = category.defaultReorderThreshold;
  if (!payload.unit) payload.unit = category.unitType;
  // Consolidated spec: SKU is generated by the system so the admin never has
  // to invent one. Product ID (_id) and barcode stay separate fields.
  if (!payload.sku) payload.sku = await generateSku(payload.category);
  if (payload.barcode && (await Product.exists({ barcode: payload.barcode }))) {
    throw new AppError(409, `Barcode ${payload.barcode} is already assigned to another product`);
  }
  if (await Product.exists({ sku: payload.sku.toUpperCase() })) {
    throw new AppError(409, `SKU ${payload.sku} already exists`);
  }

  let product = await Product.create(payload);
  product = await product.populate('createdBy', 'name role');

  if (product.currentStock > 0) {
    await InventoryLog.create({
      product: product._id,
      productName: product.name,
      sku: product.sku,
      category: product.category,
      type: INVENTORY_LOG_TYPES.PURCHASE,
      previousStock: 0,
      quantityDelta: product.currentStock,
      resultingStock: product.currentStock,
      reason: 'Initial stock on product creation',
      actor: user._id,
      branch: product.branch,
    });
  }

  await logAction({ actorUser: user, action: 'product.create', entityType: 'Product', entityId: product._id, after: payload });
  return product;
}

async function updateProduct(id, body, user) {
  if (body.category) await getCategoryOrThrow(body.category);
  const existing = await Product.findById(id);
  if (!existing) throw new AppError(404, 'Product not found');
  const before = Object.fromEntries(Object.keys(body).map((k) => [k, existing.get(k)]));

  const update = normaliseIdentifiers(body);
  if (update.barcode && (await Product.exists({ barcode: update.barcode, _id: { $ne: existing._id } }))) {
    throw new AppError(409, `Barcode ${update.barcode} is already assigned to another product`);
  }
  const product = await Product.findByIdAndUpdate(id, update, { new: true, runValidators: true }).populate('createdBy', 'name role');
  await logAction({ actorUser: user, action: 'product.update', entityType: 'Product', entityId: product._id, before, after: body });
  return product;
}

// Spec §2 "Delete inventory / products" (admin, superadmin). Soft delete:
// the record stays for historical sales and reports (spec §4.1 rule 2).
async function deleteProduct(id, user) {
  const product = await Product.findById(id);
  if (!product) throw new AppError(404, 'Product not found');
  if (!product.isActive) return product;

  product.isActive = false;
  await product.save();
  await logAction({
    actorUser: user,
    action: 'product.delete',
    entityType: 'Product',
    entityId: product._id,
    before: { isActive: true },
    after: { isActive: false },
  });
  return product;
}

async function adjustStock(id, { delta, reason }, user) {
  const before = await Product.findById(id, 'currentStock');
  const { product, log } = await applyStockChange({
    productId: id,
    delta,
    type: INVENTORY_LOG_TYPES.ADJUSTMENT,
    reason,
    actor: user._id,
    actorRole: user.role,
    branch: user.branch,
  });

  await logAction({
    actorUser: user,
    action: 'inventory.adjust',
    entityType: 'Product',
    entityId: product._id,
    before: { currentStock: before ? before.currentStock : undefined },
    after: { currentStock: product.currentStock },
    details: { delta, reason },
  });
  return { product, log };
}

module.exports = { createProduct, updateProduct, deleteProduct, adjustStock };
